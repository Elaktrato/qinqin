// Shared by the suites of the emulator driver (#37): seed data through the API and a generated strokes pack.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { randomBytes } from 'node:crypto';
import { epub } from '../../../web/e2e/support/epub.ts';
import { sleep, waitFor } from '../lib.mjs';

/**
 * The packs the touch suite needs: a strokes pack of two characters with two straight strokes each (hanzi-writer format: 1024 box, y up, baseline
 * offset 900). They are not the real stroke orders: the pads only need a reference to judge swipes against. 十 and
 * 本 are the characters of the touch suite (本 is in the fixture dictionary).
 */
export function strokesPack(dir) {
	mkdirSync(dir, { recursive: true });
	const rect = (x0, y0, x1, y1) => `M ${x0} ${y0} L ${x1} ${y0} L ${x1} ${y1} L ${x0} ${y1} Z`;
	const data = () => ({
		strokes: [rect(120, 400, 900, 470), rect(480, 60, 550, 800)],
		medians: [
			[[140, 435], [520, 435], [880, 435]],
			[[515, 780], [515, 420], [515, 80]]
		],
		radStrokes: []
	});
	const lines = ['十', '本'].map((char) => JSON.stringify({ char, data: data() })).join('\n') + '\n';
	writeFileSync(join(dir, 'strokes.jsonl.gz'), gzipSync(Buffer.from(lines)));
	// A one-entry Japanese dictionary for the writing card (十 is not in the fixture dictionary).
	const dict = join(dir, '..', 'extra-dict');
	mkdirSync(dict, { recursive: true });
	writeFileSync(join(dict, 'dictionary.json'), JSON.stringify({ entries: [{ written: '十', kind: 'word', readings: [{ type: 'kana', value: 'じゅう' }], glosses: ['ten'] }] }));
	writeFileSync(join(dict, 'manifest.json'), JSON.stringify({ id: 'e2e-android-ja', name: 'E2E extra Japanese entries (generated)', version: '1', type: 'dictionary', language: 'ja', license: 'CC0-1.0', attribution: 'Generated by the emulator driver', format: 'json' }, null, 2));
	writeFileSync(
		join(dir, 'manifest.json'),
		JSON.stringify({ id: 'e2e-strokes', name: 'E2E strokes (generated)', version: '1', type: 'strokes', languages: ['ja', 'zh'], license: 'CC0-1.0', attribution: 'Generated by the emulator driver', format: 'hanzi-writer-jsonl-gz' }, null, 2)
	);
	return [dir, dict];
}

const DAY = 86_400_000;
const CROCKFORD = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
export function ulid(time) {
	let head = '';
	let t = time;
	for (let i = 0; i < 10; i++) {
		head = CROCKFORD[t % 32] + head;
		t = Math.floor(t / 32);
	}
	let tail = '';
	for (const byte of randomBytes(16)) tail += CROCKFORD[byte % 32];
	return head + tail;
}

/** Logs a learner in through the API; returns { token, ws: {ja, zh}, api }. */
export async function apiLogin(ctx, user) {
	const res = await fetch(`${ctx.HOST}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: user.username, password: user.password, deviceName: 'android-e2e-api' }) });
	const body = await res.json();
	if (body.status !== 'ok' || !body.token) throw new Error(`login ${user.username}: ${JSON.stringify({ ...body, token: undefined })}`);
	user.token = body.token;
	user.api = ctx.api(body.token);
	user.ws = Object.fromEntries((await user.api('/api/workspaces')).map((w) => [w.language, w.id]));
	return user;
}

/**
 * Puts cards (oldest first) in the General deck of a workspace, with `cardTypes` for General when given; waits until a
 * pull round ships them (rows stamped within the second of the page load arrive only with the next round).
 * specs: { kind: 'vocab'|'reverse'|'writing'|'tone', written, reviewedDaysAgo? }
 */
export async function addCards(user, language, specs, cardTypes = null) {
	const ws = user.ws[language];
	const now = Date.now();
	const stamp = new Date(now).toISOString();
	const rows = [];
	const events = [];
	for (const [i, c] of specs.entries()) {
		const hits = await user.api(`/api/search?q=${encodeURIComponent(c.written)}&lang=${language}`);
		const entryId = hits.find((h) => h.written === c.written)?.id;
		if (!entryId) throw new Error(`no dictionary entry for ${c.written}`);
		const id = `c-${c.kind}-${entryId}`;
		rows.push({ workspaceId: ws, id, kind: c.kind, entryId, written: c.written, entryKind: null, sentenceId: null, skipKinds: [], deckIds: ['general'], createdAt: new Date(now - 10 * DAY + i * 1000).toISOString(), extra: {}, updatedAt: stamp, deletedAt: null });
		if (c.reviewedDaysAgo !== undefined) {
			const ts = now - c.reviewedDaysAgo * DAY + i * 1000;
			events.push({ id: ulid(ts), workspaceId: ws, device: 'e2e', ts: new Date(ts).toISOString(), type: 'review', payload: { cardId: id, mode: c.kind, grade: 4 } });
		}
	}
	const deckSettings = cardTypes ? [{ workspaceId: ws, deckId: 'general', cardTypes, newOrder: null, extra: {}, updatedAt: stamp, deletedAt: null }] : [];
	await user.api('/api/sync/push', { cards: rows, deckSettings, events });
	const until = Date.now() + 8000;
	for (;;) {
		const page = await user.api(`/api/sync/pull?v=2&collections=cards&limit=2000&workspace=${ws}`);
		const shipped = new Set(page.collections.cards.map((c) => c.id));
		if (rows.every((r) => shipped.has(r.id))) return rows.map((r) => r.id);
		if (Date.now() > until) throw new Error('pushed cards never appeared in a pull round');
		await sleep(150);
	}
}

/** The review events of a workspace (all pages). */
export async function reviewsOf(user, language) {
	const ws = user.ws[language];
	const out = [];
	let path = `/api/events?limit=500&workspace=${ws}`;
	for (;;) {
		const page = await user.api(path);
		out.push(...page.events.filter((e) => e.type === 'review'));
		if (!page.more || !page.next) return out;
		path = `/api/events?page=${encodeURIComponent(page.next)}&workspace=${ws}`;
	}
}

/** Uploads a one-chapter epub to a workspace's library; returns the book id. */
export async function addBook(ctx, user, language, title, paragraphs) {
	const form = new FormData();
	form.set('workspace', String(user.ws[language]));
	form.set('file', new Blob([new Uint8Array(epub(title, language, paragraphs))]), 'book.epub');
	const res = await ctx.rawApi(user.token)('/api/library/upload', { method: 'POST', body: form });
	if (!res.ok) throw new Error(`upload: ${res.status} ${(await res.text()).slice(0, 200)}`);
	return (await res.json()).id;
}

/** Sets the deck's card types by pushing a newer deck-settings row. */
export async function setCardTypes(user, language, cardTypes) {
	const stamp = new Date().toISOString();
	await user.api('/api/sync/push', { cards: [], deckSettings: [{ workspaceId: user.ws[language], deckId: 'general', cardTypes, newOrder: null, extra: {}, updatedAt: stamp, deletedAt: null }], events: [] });
}

/** Retries `fn` after relaunching the app when the page died (Google Play services may kill it on the emulator image). */
export async function resilient(ctx, label, fn, { attempts = 2 } = {}) {
	let last;
	for (let i = 1; i <= attempts; i++) {
		try {
			return await fn(i);
		} catch (err) {
			last = err;
			const dead = /socket closed|no answer|timeout/i.test(String(err.message)) || !(await ctx.cdp.eval('1+1').catch(() => null));
			if (i === attempts || !dead) break;
			console.log(`${label}: attempt ${i} failed (${err.message}); relaunching`);
			ctx.cdp.close();
			ctx.cdp = (await ctx.coldStart(`retry_${label.replace(/\W+/g, '_')}`)).cdp;
		}
	}
	throw last;
}

/**
 * useLearner: makes the app signed in as `user` (through the API token, like the first sign-in of the driver) and
 * starts it on Home. Wipes the previous learner's local state (storage, IndexedDB) so nothing leaks over.
 */
export async function useLearner(ctx, user) {
	if (!user.token) await apiLogin(ctx, user);
	if (ctx.signedAs === user.username) return user;
	await ctx.cdp.eval(`(async () => {
		localStorage.clear();
		for (const d of (await indexedDB.databases?.()) || []) indexedDB.deleteDatabase(d.name);
		localStorage.setItem('qinqin.token', ${JSON.stringify(user.token)});
		location.assign('/');
	})()`);
	await sleep(1500);
	await waitFor('Home after the switch', async () => (await ctx.cdp.eval(`[...document.querySelectorAll('nav[aria-label=Main], header')].some((n) => n.getClientRects().length > 0) && location.pathname === '/'`)), { timeout: 40_000, interval: 500 });
	ctx.signedAs = user.username;
	return user;
}

/** The mode radio of Settings, Appearance: the real theme switch. mode: 'light' | 'dark'. */
export async function setMode(ctx, mode, click) {
	await ctx.cdp.eval("location.assign('/settings?tab=appearance')");
	await waitFor('the appearance tab', () => ctx.cdp.eval(`!!document.querySelector('input[name=appearance-mode][value=${mode}]')`), { timeout: 30_000 });
	await click(ctx.cdp, `document.querySelector('input[name=appearance-mode][value=${mode}]').closest('label')`);
	await waitFor(`the ${mode} scheme`, () => ctx.cdp.eval(`document.documentElement.dataset.scheme === ${JSON.stringify(mode === 'dark' ? 'dark' : 'light')}`), { timeout: 15_000, interval: 300 });
	return ctx.cdp.eval('({ scheme: document.documentElement.dataset.scheme, bg: getComputedStyle(document.documentElement).getPropertyValue("--bg").trim(), chrome: getComputedStyle(document.documentElement).getPropertyValue("--chrome").trim() })');
}
