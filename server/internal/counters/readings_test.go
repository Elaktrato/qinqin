// TestClassicReadings: the sound changes the issue names, by hand.
func TestClassicReadings(t *testing.T) {
	cases := []struct {
		counter, number string
		answers         []string
		mistakes        []string
	}{
		{"hon", "1", []string{"いっぽん"}, []string{"いちほん"}},
		{"hon", "3", []string{"さんぼん"}, []string{"さんほん", "さんぽん"}},
		{"hon", "6", []string{"ろっぽん"}, []string{"ろくほん"}},
		{"hon", "10", []string{"じゅっぽん", "じっぽん"}, nil},
		{"hon", "nan", []string{"なんぼん"}, []string{"なんほん"}},
		{"hon", "4", []string{"よんほん"}, []string{"よんぼん", "よんぽん"}},
		{"nin", "1", []string{"ひとり"}, []string{"いちにん"}},
		{"nin", "2", []string{"ふたり"}, []string{"ににん"}},
		{"nin", "4", []string{"よにん"}, []string{"よんにん"}},
		{"nichi", "20", []string{"はつか"}, []string{"にじゅうにち"}},
		{"nichi", "1", []string{"ついたち"}, []string{"いちにち"}},
		{"kai-floor", "3", []string{"さんがい", "さんかい"}, nil},
		{"ken", "3", []string{"さんげん"}, []string{"さんけん"}},
		{"satsu", "6", []string{"ろくさつ"}, []string{"ろっさつ"}},
		{"satsu", "8", []string{"はっさつ"}, []string{"はちさつ"}},
		{"ko", "6", []string{"ろっこ"}, []string{"ろくこ"}},
		{"fun", "3", []string{"さんぷん"}, []string{"さんふん", "さんぶん"}},
		{"soku", "3", []string{"さんぞく"}, []string{"さんそく"}},
		{"tou", "1", []string{"いっとう"}, []string{"いちとう"}},
		{"ji", "4", []string{"よじ"}, []string{"よんじ"}},
		{"tsu", "3", []string{"みっつ"}, nil},
	}
	for _, c := range cases {
		r, ok := counters.ReadingsOf(c.counter, c.number)
		if !ok {
			t.Errorf("%s:%s: no readings", c.counter, c.number)
			continue
		}
		var got []string
		for _, a := range r.Answers {
			got = append(got, a.Reading)
		}
		if !slices.Equal(got, c.answers) {
			t.Errorf("%s:%s: answers %v, want %v", c.counter, c.number, got, c.answers)
		}
		var wrong []string
		for _, m := range r.Mistakes {
			wrong = append(wrong, m.Reading)
		}
		for _, m := range c.mistakes {
			if !slices.Contains(wrong, m) {
				t.Errorf("%s:%s: mistakes %v lack %s", c.counter, c.number, wrong, m)
			}
		}
		for _, a := range got {
			if slices.Contains(wrong, a) {
				t.Errorf("%s:%s: %s is an answer and a mistake", c.counter, c.number, a)
			}
		}
	}
}

const readingsFixture = "readings.json"

type readingsFile struct {
	Version  int                        `json:"version"`
	Rule     string                     `json:"rule"`
	Doc      string                     `json:"doc"`
	Counters []counters.CounterReadings `json:"counters"`
}

// TestReadingsContract: readings.json is the whole table's readings (and
// the answer of GET /api/drills/counters). UPDATE_COUNTERS_FIXTURE=1
// writes it.
func TestReadingsContract(t *testing.T) {
	got := readingsFile{Version: 1, Rule: "counters/readings",
		Doc: "Every counter of the Japanese counters table (server/internal/counters/table/counters-ja.json) with each asked number's prompt, kanji form, readings (canonical first, then the accepted ones) and common mistakes (README, \"Readings\"); also the answer of GET /api/drills/counters. Generated by the Go test with UPDATE_COUNTERS_FIXTURE=1 and reviewed by hand and by teacher agents (table/REVIEW.md). Go: server/internal/counters/readings_test.go; web: apps/web/src/lib/features/practice/counters/check.test.ts, words.test.ts.",
		Counters: counters.AllReadings()}
	path := filepath.Join(contractDir, readingsFixture)
	if os.Getenv("UPDATE_COUNTERS_FIXTURE") == "1" {
		var buf bytes.Buffer
		enc := json.NewEncoder(&buf)
		enc.SetEscapeHTML(false)
		enc.SetIndent("", " ")
		if err := enc.Encode(got); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	var fx readingsFile
	decodeFixture(t, readingsFixture, &fx)
	a, _ := json.Marshal(fx)
	b, _ := json.Marshal(got)
	if !bytes.Equal(a, b) {
		t.Fatalf("readings.json is stale: run with UPDATE_COUNTERS_FIXTURE=1 and review the diff")
	}
}

// TestTableInvariants: every noun's counters exist, no counter id or noun
// repeats, every counter has numbers and every number at least one answer.
func TestTableInvariants(t *testing.T) {
	tab := counters.JapaneseTable()
	if tab.License != "CC-BY-4.0" {
		t.Errorf("license = %q", tab.License)
	}
	ids := map[string]bool{}
	for _, c := range tab.Counters {
		if ids[c.ID] {
			t.Errorf("counter %s twice", c.ID)
		}
		ids[c.ID] = true
		if _, _, ok := counters.ParseReadingItem(counters.ReadingItem(c.ID, "1")); !ok {
			t.Errorf("counter id %q makes no item key", c.ID)
		}
	}
	seen := map[string]bool{}
	for _, n := range tab.Nouns {
		key := n.Written + "|" + n.Reading
		if seen[key] {
			t.Errorf("noun %s twice", key)
		}
		seen[key] = true
		if len(n.Counters) == 0 {
			t.Errorf("noun %s has no counter", key)
		}
		for _, id := range n.Counters {
			if !ids[id] {
				t.Errorf("noun %s: unknown counter %s", key, id)
			}
		}
	}
	for _, c := range counters.AllReadings() {
		if len(c.Numbers) == 0 {
			t.Errorf("counter %s asks no number", c.ID)
		}
		for _, n := range c.Numbers {
			if len(n.Answers) == 0 {
				t.Errorf("%s:%s has no answer", c.ID, n.Number)
			}
			for _, a := range append(slices.Clone(n.Answers), n.Mistakes...) {
				if a.Romaji == "" {
					t.Errorf("%s:%s: %s has no romaji", c.ID, n.Number, a.Reading)
				}
			}
		}
	}
}
