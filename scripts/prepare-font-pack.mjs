/** Names a slice may not carry outside its copyright and licence entries (Reserved Font Names, trademarks, originals). */
export const FORBIDDEN_NAMES = ['Noto', 'Source', 'LXGW', '霞鹜', '霞鶩', '落霞孤鹜', '落霞孤鶩', 'Klee'];
const FACE_NAMES = { sans: 'Sans', serif: 'Serif', kai: 'Kai' };
const SCRIPT_NAMES = { Hans: 'SC', Hant: 'TC', Jpan: 'JP' };

/** familyName is the renamed family of a face: `qinqin Kai SC`. */
export function familyName(face, script) {
	return `qinqin ${FACE_NAMES[face]} ${SCRIPT_NAMES[script]}`;
}

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

// --- the slice table ---------------------------------------------------------

/** Slice 0 per script: the code points every page needs first. */
const BASE = {
	Hans: [[0x20, 0x7e], [0x3000, 0x303f], [0xff00, 0xffef]],
	Hant: [[0x20, 0x7e], [0x3000, 0x303f], [0xff00, 0xffef]],
	Jpan: [[0x20, 0x7e], [0x3000, 0x303f], [0x3040, 0x30ff], [0xff00, 0xffef]]
};

function levelChars(pack, levels) {
	const doc = JSON.parse(readFileSync(join(root, 'plugins/data', pack, 'levels.json'), 'utf8'));
	const out = [];
	for (const l of doc.levels) if (!levels || levels.includes(l.name)) out.push(...l.entries);
	return out;
}

function dedupe(chars) {
	const seen = new Set();
	return chars.filter((c) => [...c].length === 1 && !seen.has(c) && seen.add(c));
}

/**
 * generateSliceTable builds the slice table from the bundled level lists:
 * Hans = tgh-chars levels 1 and 2 in serial order; Hant = the same
 * characters through OpenCC (mainland to Taiwan forms, opencc-js from
 * apps/web/node_modules); Jpan = joyo-grades, then jlpt-kanji.
 */
export async function generateSliceTable() {
	const hans = dedupe(levelChars('tgh-chars', ['Level 1', 'Level 2']));
	const require = createRequire(join(root, 'apps/web/package.json'));
	let OpenCC;
	try {
		OpenCC = require('opencc-js');
	} catch {
		throw new Error('opencc-js is missing: run `npm --prefix apps/web ci` first');
	}
	const toTW = OpenCC.Converter({ from: 'cn', to: 'tw' });
	const hant = dedupe(hans.map((c) => toTW(c)));
	const jpan = dedupe([...levelChars('joyo-grades'), ...levelChars('jlpt-kanji')]);
	return {
		version: 1,
		_doc:
			'The slice table of scripts/prepare-font-pack.mjs (generated by --slices; do not edit). base: slice 0 of each script as [first, last] code point pairs. ranked: characters in rank order, cut into slices of chunkRanked after slice 0 (Hans: tgh-chars levels 1-2; Hant: the same through OpenCC cn->tw; Jpan: joyo-grades then jlpt-kanji). The font\'s other code points follow in ascending order in slices of chunkRest.',
		chunkRanked: 200,
		chunkRest: 500,
		base: BASE,
		ranked: { Hans: hans.join(''), Hant: hant.join(''), Jpan: jpan.join('') }
	};
}

export function formatSliceTable(t) {
	const lines = [
		'{',
		` "version": ${t.version},`,
		` "_doc": ${JSON.stringify(t._doc)},`,
		` "chunkRanked": ${t.chunkRanked},`,
		` "chunkRest": ${t.chunkRest},`,
		` "base": ${JSON.stringify(t.base)},`,
		' "ranked": {',
		Object.entries(t.ranked)
			.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`)
			.join(',\n'),
		' }',
		'}'
	];
	return lines.join('\n') + '\n';
}

/**
 * planSlices cuts a font's code points into slices: [[code point]] in
 * slice order, every code point in exactly one slice, empty slices dropped.
 */
export function planSlices(points, script, table) {
	const have = new Set(points);
	const used = new Set();
	const slices = [];
	const base = [];
	for (const [lo, hi] of table.base[script]) {
		for (let c = lo; c <= hi; c++) if (have.has(c) && !used.has(c)) (base.push(c), used.add(c));
	}
	if (base.length) slices.push(base);
	let chunk = [];
	for (const ch of table.ranked[script]) {
		const c = ch.codePointAt(0);
		if (!have.has(c) || used.has(c)) continue;
		used.add(c);
		chunk.push(c);
		if (chunk.length === table.chunkRanked) (slices.push(chunk), (chunk = []));
	}
	if (chunk.length) slices.push(chunk);
	chunk = [];
	for (const c of points) {
		if (used.has(c)) continue;
		chunk.push(c);
		if (chunk.length === table.chunkRest) (slices.push(chunk), (chunk = []));
	}
	if (chunk.length) slices.push(chunk);
	return slices.map((s) => [...s].sort((a, b) => a - b));
}

// --- renaming ----------------------------------------------------------------

const KEEP_IDS = new Set([0, 2, 5, 13, 14, 17]);

/**
 * renameFont rewrites the name table of a TrueType font (Ruling 3): the
 * family (1, 16), full (4), PostScript (6), unique (3) and variations
 * PostScript prefix (25) names become the qinqin family; copyright (0),
 * subfamily (2, 17), version (5), licence (13, 14) and the axis/instance
 * names (256+) are kept with the original's family names replaced; every
 * other name is dropped. Throws when a kept name still carries a name of
 * FORBIDDEN_NAMES (outside copyright and licence).
 */
export function renameFont(ttf, family) {
	const font = parseSfnt(ttf);
	if (font.tables.has('CFF ') || font.tables.has('CFF2')) {
		throw new Error('CFF-flavoured fonts carry names in the CFF table too; only TrueType (glyf) sources are supported');
	}
	const records = readNames(font.tables.get('name')).filter((r) => r.platformID === 3 && r.languageID === 0x409);
	const get = (id) => records.find((r) => r.nameID === id)?.value;
	const oldFamily = get(16) ?? get(1) ?? '';
	const oldPS = (get(25) ?? get(6) ?? '').split('-')[0];
	const ps = family.replace(/ /g, '');
	const sub = get(2) ?? 'Regular';
	const typoSub = get(17);
	const swap = (s) => {
		let out = s;
		if (oldFamily) out = out.split(oldFamily).join(family);
		if (oldPS) out = out.split(oldPS).join(ps);
		return out;
	};
	const out = [];
	for (const r of records) {
		if (KEEP_IDS.has(r.nameID) || r.nameID >= 256) {
			out.push({ nameID: r.nameID, value: r.nameID === 0 || r.nameID === 13 || r.nameID === 14 ? r.value : swap(r.value) });
		}
	}
	const fullSub = typoSub ?? sub;
	const set = (id, value) => {
		const i = out.findIndex((r) => r.nameID === id);
		if (i >= 0) out.splice(i, 1);
		out.push({ nameID: id, value });
	};
	set(1, family);
	set(4, fullSub === 'Regular' ? family : `${family} ${fullSub}`);
	set(6, `${ps}-${fullSub.replace(/ /g, '')}`);
	set(3, `${get(5) ?? '1.0'};qinqin;${ps}-${fullSub.replace(/ /g, '')}`);
	if (get(16) !== undefined) set(16, family);
	if (get(25) !== undefined) set(25, ps);
	for (const r of out) {
		if (r.nameID === 0 || r.nameID === 13 || r.nameID === 14) continue;
		for (const word of FORBIDDEN_NAMES) {
			if (r.value.includes(word)) throw new Error(`name ID ${r.nameID} still says "${r.value}" (contains ${word})`);
		}
	}
	font.tables.set('name', buildNames(out));
	return buildSfnt(font);
}

// --- building ----------------------------------------------------------------

/** loadTools loads the subsetter from scripts/fonts/node_modules, or explains how to install it. */
export function loadTools() {
	const require = createRequire(join(root, 'scripts/fonts/package.json'));
	try {
		return { subsetFont: require('subset-font'), fontverter: require('fontverter') };
	} catch {
		throw new Error('the font tools are missing: run `npm --prefix scripts/fonts ci` first');
	}
}

function checkPin(what, buf, pin) {
	const got = sha256(buf);
	if (got !== pin.sha256 || (pin.bytes !== undefined && buf.length !== pin.bytes)) {
		throw new Error(`${what}: sha256 ${got} (${buf.length} bytes) does not match the pinned ${pin.sha256}${pin.bytes ? ` (${pin.bytes} bytes)` : ''}; refusing to build`);
	}
}

async function fetchPinned(url, pin, cacheDir, name) {
	const path = join(cacheDir, name);
	if (existsSync(path)) {
		const buf = readFileSync(path);
		if (sha256(buf) === pin.sha256) return buf;
	}
	const resp = await fetch(url);
	if (!resp.ok) throw new Error(`${url}: HTTP ${resp.status}`);
	const buf = Buffer.from(await resp.arrayBuffer());
	checkPin(url, buf, pin);
	mkdirSync(cacheDir, { recursive: true });
	writeFileSync(path, buf);
	return buf;
}

/**
 * buildPack writes the pack `id` of `source` into out. fonts and license
 * are the upstream bytes (checked against the source's pins); table is
 * the slice table; tools the loaded subsetter. Returns {manifest, faces,
 * bytes} after checking the written pack as the server would.
 */
export async function buildPack({ id, source, fonts, license, table, tools, out, log = () => {} }) {
	if (fonts.length !== source.fonts.length) throw new Error(`${id}: ${source.fonts.length} font files expected`);
	source.fonts.forEach((pin, i) => checkPin(pin.file, fonts[i], pin));
	checkPin('OFL.txt', license, source.license);
	if (!/SIL OPEN FONT LICENSE Version 1\.1/.test(license.toString('utf8'))) throw new Error('OFL.txt is not the SIL Open Font License 1.1');

	const family = familyName(source.face, source.script);
	rmSync(out, { recursive: true, force: true });
	mkdirSync(join(out, 'slices'), { recursive: true });
	const faces = [];
	let bytes = 0;
	let version = '';
	for (const ttf of fonts) {
		const font = parseSfnt(ttf);
		const names = readNames(font.tables.get('name'));
		const preserve = [...new Set(names.map((r) => r.nameID))];
		version ||= (names.find((r) => r.nameID === 5 && r.platformID === 3)?.value ?? '').match(/\d+(\.\d+)*/)?.[0] ?? '0';
		const weight = weightOf(font.tables);
		const plan = planSlices(readCmap(font.tables.get('cmap')), source.script, table);
		const face = { face: source.face, script: source.script, original: source.original, weight, style: 'normal', slices: [] };
		for (const [n, points] of plan.entries()) {
			const text = String.fromCodePoint(...points);
			const subset = await tools.subsetFont(ttf, text, { targetFormat: 'truetype', preserveNameIds: preserve });
			const renamed = renameFont(subset, family);
			const woff2 = Buffer.from(await tools.fontverter.convert(renamed, 'woff2'));
			const sha = sha256(woff2);
			writeFileSync(join(out, 'slices', `${sha}.woff2`), woff2);
			face.slices.push({ file: `slices/${sha}.woff2`, unicodeRange: unicodeRange(points) });
			bytes += woff2.length;
			log(`${family} ${weight}: slice ${n + 1}/${plan.length}, ${points.length} code points, ${woff2.length} bytes`);
		}
		faces.push(face);
	}
	const name = `${family} (${source.original}, subset)`;
	const manifest = {
		id,
		name,
		version: `${version}-q${SLICE_REVISION}`,
		type: 'font',
		license: LICENSE,
		attribution: `${source.original} by ${source.authors} (SIL OFL 1.1), ${source.upstream}; subset into WOFF2 slices and renamed ${family} by qinqin`,
		notice: `${family} is a modified version (subset into slices by Unicode range, renamed) of ${source.original} by ${source.authors}, ${source.upstream}, under the SIL Open Font License 1.1. As the licence asks of modified versions, the slices carry their own name; the original name is used here only to credit its authors.`,
		format: 'font-slices'
	};
	writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
	writeFileSync(join(out, 'faces.json'), JSON.stringify({ version: 1, faces }, null, 1) + '\n');
	writeFileSync(join(out, 'LICENSE'), license);
	writeFileSync(
		join(out, 'ATTRIBUTION.md'),
		`# ${name}\n\n${family} is a modified version of **${source.original}** by ${source.authors} (${source.upstream}), ` +
			`licensed under the SIL Open Font License, Version 1.1 (LICENSE, the original's OFL.txt byte for byte).\n\n` +
			`Modification: subset into ${faces.reduce((n, f) => n + f.slices.length, 0)} WOFF2 slices by Unicode range ` +
			`(scripts/prepare-font-pack.mjs, slice table revision ${SLICE_REVISION}) and renamed ${family}; the copyright and ` +
			`licence entries of each font are unchanged. Source: ${source.fonts.map((f) => f.url).join(', ')} ` +
			`(${source.ref}).\n`
	);
	checkPackDir(out);
	return { manifest, faces, bytes };
}

// --- command line --------------------------------------------------------------

function usage(msg) {
	if (msg) console.error(msg);
	console.error(
		'usage: node scripts/prepare-font-pack.mjs --source <' + Object.keys(SOURCES).join('|') + '> --out <dir>\n' +
			'         [--face sans|serif|kai] [--script Hans|Hant|Jpan] [--cache <dir>] [--font <file>]... [--license <file>]\n' +
			'       node scripts/prepare-font-pack.mjs --slices [--check]'
	);
	process.exit(2);
}

function parseArgs(argv) {
	const o = { fonts: [], cache: join(root, 'plugins/data-fonts/.cache') };
	for (let i = 0; i < argv.length; i++) {
		const a = argv[i];
		if (a === '--slices' || a === '--check') o[a.slice(2)] = true;
		else if (['--source', '--out', '--face', '--script', '--cache', '--license', '--font'].includes(a)) {
			const v = argv[++i];
			if (!v) usage(`${a} needs a value`);
			if (a === '--font') o.fonts.push(v);
			else o[a.slice(2)] = v;
		} else usage(`unknown argument ${a}`);
	}
	return o;
}

async function main(argv) {
	const o = parseArgs(argv);
	if (o.slices) {
		const text = formatSliceTable(await generateSliceTable());
		if (o.check) {
			if (readFileSync(SLICES_FILE, 'utf8') !== text) throw new Error(`${SLICES_FILE} is stale: run --slices`);
			console.log('slice table up to date');
		} else {
			writeFileSync(SLICES_FILE, text);
			console.log(`wrote ${SLICES_FILE}`);
		}
		return;
	}
	const source = SOURCES[o.source];
	if (!source) usage(`--source must be one of ${Object.keys(SOURCES).join(', ')}`);
	if (!o.out) usage('--out is required');
	if (o.face && o.face !== source.face) usage(`--face ${o.face}: ${o.source} is ${source.face}`);
	if (o.script && o.script !== source.script) usage(`--script ${o.script}: ${o.source} is ${source.script}`);
	if (o.fonts.length && o.fonts.length !== source.fonts.length) usage(`${o.source} has ${source.fonts.length} font file(s)`);
	const tools = loadTools();
	const fonts = [];
	for (const [i, pin] of source.fonts.entries()) {
		fonts.push(o.fonts[i] ? readFileSync(o.fonts[i]) : await fetchPinned(pin.url, pin, o.cache, pin.file));
	}
	const license = o.license ? readFileSync(o.license) : await fetchPinned(source.license.url, source.license, o.cache, `${o.source}-OFL.txt`);
	const table = JSON.parse(readFileSync(SLICES_FILE, 'utf8'));
	const res = await buildPack({ id: o.source, source, fonts, license, table, tools, out: o.out, log: (l) => console.error(l) });
	const slices = res.faces.reduce((n, f) => n + f.slices.length, 0);
	console.log(`${o.source}: ${res.faces.length} face(s), ${slices} slices, ${res.bytes} bytes of WOFF2 in ${o.out}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	main(process.argv.slice(2)).catch((err) => {
		console.error(`prepare-font-pack: ${err.message}`);
		process.exit(1);
	});
}
