#!/usr/bin/env node
// Writes src/lib/ui/icons/lucide.ts: the path data of the icons qinqin uses,
// taken from a downloaded `lucide-static` package (ISC; its Feather-derived
// icons MIT). Never run by the build — run it by hand when an icon is added:
//
//   mkdir /tmp/lucide && cd /tmp/lucide
//   curl -sSO https://registry.npmjs.org/lucide-static/-/lucide-static-1.66.0.tgz
//   tar xzf lucide-static-1.66.0.tgz
//   node apps/web/scripts/vendor-icons.mjs /tmp/lucide/package
//
// Then copy the package's LICENSE byte for byte to static/LUCIDE-LICENSE.TXT
// when the version changes (lib/ui/icons/lucide.test.ts pins its hash), and
// keep docs/sources.md "Icons" in step. Only the data travels: no npm
// dependency, and the stroke width is ours (Icon.svelte draws at 1.5).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Our icon name → the Lucide icon drawn for it. Sorted by our name. */
export const WANTED = {
	add: 'plus',
	admin: 'shield-check',
	alert: 'circle-alert',
	'arrow-down': 'arrow-down',
	'arrow-up': 'arrow-up',
	back: 'chevron-left',
	bookmark: 'bookmark',
	check: 'check',
	close: 'x',
	contents: 'list',
	delete: 'trash',
	display: 'type',
	draw: 'signature',
	edit: 'pencil',
	'expand-down': 'chevron-down',
	'expand-up': 'chevron-up',
	external: 'external-link',
	flag: 'flag',
	forward: 'chevron-right',
	highlight: 'highlighter',
	home: 'house',
	info: 'info',
	journal: 'notebook-pen',
	library: 'library',
	map: 'map',
	menu: 'menu',
	minus: 'minus',
	more: 'ellipsis',
	palette: 'palette',
	parts: 'layout-panel-left',
	pause: 'pause',
	play: 'play',
	plugin: 'puzzle',
	reader: 'book-open',
	repeat: 'repeat',
	search: 'search',
	settings: 'settings',
	'sign-in': 'log-in',
	'sign-out': 'log-out',
	sound: 'volume-2',
	stats: 'chart-no-axes-column',
	study: 'square-stack',
	user: 'circle-user',
	words: 'case-sensitive'
};

function main() {
	const dir = process.argv[2];
	if (!dir) {
		console.error('usage: node scripts/vendor-icons.mjs <lucide-static package dir>');
		process.exit(2);
	}
	const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
	const nodes = JSON.parse(readFileSync(join(dir, 'icon-nodes.json'), 'utf8'));
	const lines = [
		`// @license lucide-static v${pkg.version} - ${pkg.license} (static/LUCIDE-LICENSE.TXT; icons derived from Feather: MIT)`,
		'// Generated by scripts/vendor-icons.mjs from the lucide-static package; do not edit by hand.',
		'// Each icon is the list of its SVG elements on the 24×24 grid; Icon.svelte draws them.',
		'',
		"export type IconElement = [tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse', attrs: Record<string, string>];",
		'',
		`export const LUCIDE_VERSION = '${pkg.version}';`,
		'',
		'/** Our name → the Lucide icon it draws (for the credits and the tests). */',
		'export const LUCIDE_NAMES = {'
	];
	for (const [ours, theirs] of Object.entries(WANTED)) lines.push(`\t${JSON.stringify(ours)}: ${JSON.stringify(theirs)},`);
	lines.push('} as const;', '', 'export type IconName = keyof typeof LUCIDE_NAMES;', '', 'export const ICONS: Record<IconName, IconElement[]> = {');
	for (const [ours, theirs] of Object.entries(WANTED)) {
		const icon = nodes[theirs];
		if (!icon) throw new Error(`lucide-static ${pkg.version} has no icon ${theirs}`);
		lines.push(`\t${JSON.stringify(ours)}: ${JSON.stringify(icon)},`);
	}
	lines.push('};', '');
	const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'ui', 'icons', 'lucide.ts');
	writeFileSync(out, lines.join('\n'));
	console.log(`wrote ${Object.keys(WANTED).length} icons to ${out}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
