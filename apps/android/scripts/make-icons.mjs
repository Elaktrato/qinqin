// Builds the launcher icon from the qinqin logo (apps/web/src/lib/assets/qinqin-logo.svg), so the icon and the
// logo cannot drift apart:
//   res/drawable/ic_launcher_foreground.xml  the logo as a vector in white, inside the adaptive icon's safe zone.
//                                            Used by the adaptive icon (API 26+), its themed "monochrome" layer
//                                            (Android 13+) and the Android 12+ splash screen.
//   res/mipmap-nodpi/ic_launcher*.png        the icon for API 24-25, which have no adaptive icons.
// Run `node scripts/make-icons.mjs` after the logo changes; icons.test.ts fails when the files are stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const LOGO = here('../../web/src/lib/assets/qinqin-logo.svg');
export const RES = here('../android/app/src/main/res/');
export const BACKGROUND = [0x0b, 0x6b, 0xcb]; // @color/ic_launcher_background

// The logo is one path of straight segments (M, L, Z) in a 1080 x 1080 box.
export function parseLogo(svg) {
	const d = /<path[^>]* d="([^"]+)"/.exec(svg)?.[1];
	if (!d) throw new Error('no path in the logo');
	const subpaths = [];
	for (const [, cmd, args] of d.matchAll(/([MLZz])([^MLZz]*)/g)) {
		if (cmd === 'M') subpaths.push([]);
		if (cmd === 'M' || cmd === 'L') {
			const n = args.match(/-?\d*\.?\d+/g).map(Number);
			for (let i = 0; i < n.length; i += 2) subpaths[subpaths.length - 1].push([n[i], n[i + 1]]);
		}
	}
	const all = subpaths.flat();
	const xs = all.map((p) => p[0]);
	const ys = all.map((p) => p[1]);
	const bbox = { x0: Math.min(...xs), y0: Math.min(...ys), x1: Math.max(...xs), y1: Math.max(...ys) };
	return { d: d.trim(), subpaths, bbox };
}

// Adaptive icon: 108 dp canvas, the round mask keeps the middle 66 dp safe. The logo is a loose circle, so its
// height may use more of the canvas than a square mark could (58 dp, centred).
const CANVAS = 108;
const LOGO_HEIGHT_DP = 58;

export function foregroundXml(logo) {
	const { bbox } = logo;
	const s = LOGO_HEIGHT_DP / (bbox.y1 - bbox.y0);
	const cx = (bbox.x0 + bbox.x1) / 2;
	const cy = (bbox.y0 + bbox.y1) / 2;
	const f = (n) => String(Number(n.toFixed(4)));
	return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icons.mjs from the qinqin logo. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${CANVAS}dp"
    android:height="${CANVAS}dp"
    android:viewportWidth="${CANVAS}"
    android:viewportHeight="${CANVAS}">
    <group
        android:translateX="${f(CANVAS / 2 - cx * s)}"
        android:translateY="${f(CANVAS / 2 - cy * s)}"
        android:scaleX="${f(s)}"
        android:scaleY="${f(s)}">
        <path
            android:fillColor="#FFFFFFFF"
            android:pathData="${logo.d}"/>
    </group>
</vector>
`;
}

// Coverage mask of the logo (non-zero winding, like the SVG) at size x size, 1 = inside.
function mask(logo, size, unitsPerPx, ox, oy) {
	const out = new Uint8Array(size * size);
	for (let y = 0; y < size; y++) {
		const yy = (y + 0.5) * unitsPerPx + oy;
		const hits = [];
		for (const sp of logo.subpaths) {
			for (let i = 0; i < sp.length; i++) {
				const [x1, y1] = sp[i];
				const [x2, y2] = sp[(i + 1) % sp.length];
				if ((y1 <= yy && yy < y2) || (y2 <= yy && yy < y1)) {
					hits.push([x1 + ((yy - y1) * (x2 - x1)) / (y2 - y1), y2 > y1 ? 1 : -1]);
				}
			}
		}
		hits.sort((a, b) => a[0] - b[0]);
		let w = 0;
		for (let i = 0; i < hits.length - 1; i++) {
			w += hits[i][1];
			if (w === 0) continue;
			const a = Math.max(0, Math.ceil((hits[i][0] - ox) / unitsPerPx - 0.5));
			const b = Math.min(size - 1, Math.floor((hits[i + 1][0] - ox) / unitsPerPx - 0.5));
			for (let x = a; x <= b; x++) out[y * size + x] = 1;
		}
	}
	return out;
}

function crc32(buf) {
	let c;
	let crc = 0xffffffff;
	for (let n = 0; n < buf.length; n++) {
		c = (crc ^ buf[n]) & 0xff;
		for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
		crc = (crc >>> 8) ^ c;
	}
	return (crc ^ 0xffffffff) >>> 0;
}

function png(size, rgba) {
	const chunk = (type, data) => {
		const body = Buffer.concat([Buffer.from(type), data]);
		const len = Buffer.alloc(4);
		len.writeUInt32BE(data.length);
		const crc = Buffer.alloc(4);
		crc.writeUInt32BE(crc32(body));
		return Buffer.concat([len, body, crc]);
	};
	const head = Buffer.alloc(13);
	head.writeUInt32BE(size, 0);
	head.writeUInt32BE(size, 4);
	head.set([8, 6, 0, 0, 0], 8); // 8 bit RGBA
	const raw = Buffer.alloc(size * (size * 4 + 1));
	for (let y = 0; y < size; y++) {
		raw[y * (size * 4 + 1)] = 0;
		rgba.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
	}
	return Buffer.concat([
		Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
		chunk('IHDR', head),
		chunk('IDAT', deflateSync(raw, { level: 9 })),
		chunk('IEND', Buffer.alloc(0))
	]);
}

// The legacy launcher icon: the logo in white on the brand blue, a rounded square or a circle, 4 x 4 supersampled.
export function legacyIcon(logo, round, size = 192) {
	const SS = 4;
	const big = size * SS;
	const { bbox } = logo;
	const logoPx = big * 0.62; // logo height in the supersampled image
	const unitsPerPx = (bbox.y1 - bbox.y0) / logoPx;
	const ox = (bbox.x0 + bbox.x1) / 2 - (big / 2) * unitsPerPx;
	const oy = (bbox.y0 + bbox.y1) / 2 - (big / 2) * unitsPerPx;
	const m = mask(logo, big, unitsPerPx, ox, oy);
	const radius = round ? big / 2 : big * 0.22;
	const inside = (x, y) => {
		const px = x + 0.5;
		const py = y + 0.5;
		const dx = Math.max(radius - px, 0, px - (big - radius));
		const dy = Math.max(radius - py, 0, py - (big - radius));
		return dx * dx + dy * dy <= radius * radius;
	};
	const rgba = Buffer.alloc(size * size * 4);
	for (let y = 0; y < size; y++) {
		for (let x = 0; x < size; x++) {
			let shape = 0;
			let ink = 0;
			for (let j = 0; j < SS; j++) {
				for (let i = 0; i < SS; i++) {
					const X = x * SS + i;
					const Y = y * SS + j;
					if (inside(X, Y)) {
						shape++;
						if (m[Y * big + X]) ink++;
					}
				}
			}
			const o = (y * size + x) * 4;
			if (shape === 0) continue;
			const t = ink / shape; // share of white within the shape
			rgba[o] = Math.round(BACKGROUND[0] + (255 - BACKGROUND[0]) * t);
			rgba[o + 1] = Math.round(BACKGROUND[1] + (255 - BACKGROUND[1]) * t);
			rgba[o + 2] = Math.round(BACKGROUND[2] + (255 - BACKGROUND[2]) * t);
			rgba[o + 3] = Math.round((255 * shape) / (SS * SS));
		}
	}
	return png(size, rgba);
}

export function build() {
	const logo = parseLogo(readFileSync(LOGO, 'utf8'));
	return {
		'drawable/ic_launcher_foreground.xml': foregroundXml(logo),
		'mipmap-nodpi/ic_launcher.png': legacyIcon(logo, false),
		'mipmap-nodpi/ic_launcher_round.png': legacyIcon(logo, true)
	};
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	for (const [file, data] of Object.entries(build())) writeFileSync(RES + file, data);
	console.log('icons written');
}
