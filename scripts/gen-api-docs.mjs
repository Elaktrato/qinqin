#!/usr/bin/env node
// Generates the wiki's API pages from the real sources:
//   docs/wiki/API-Routes.md  <- apps/web/src/lib/pwa/sw/routes.fixture.json
//                               (kept equal to the Go route table by TestRoutesFixture)
//                               and docs/contracts/auth/tokens-routes.json (the Token
//                               column; kept equal by TestTokenRoutesFixture)
//   docs/wiki/API-Errors.md  <- docs/contracts/auth/errors.json
// Usage: node scripts/gen-api-docs.mjs [--check] [repo-root]
//   --check  write nothing; exit 1 when a committed page differs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ACCESS = [
	['public', 'Public', 'No session needed. A restricted session is treated as anonymous.'],
	['user', 'Signed-in user', 'A full session (`Authorization: Bearer <token>`).'],
	['session', 'Any session', 'Also open to a restricted session (forced password change, required two-step enrolment) where the route allows it.'],
	['admin', 'Administrator', 'A full administrator session.'],
	['admin-signed-in', 'Administrator (signed-in check)', 'Custom AI endpoint management: a signed-in user is required first, then the handler answers 403 `forbidden` to non-administrators.']
];

// tokenLabel words a route's access token rule for the Token column.
function tokenLabel(rule) {
	if (!rule) return '—';
	const ws = { any: '', query: ' (workspace)', refused: ' (all)' }[rule.workspace];
	if ((rule.scope !== 'read' && rule.scope !== 'write') || ws === undefined) {
		throw new Error(`unknown token rule for ${rule.pattern}: ${rule.scope}/${rule.workspace}`);
	}
	return rule.scope + ws;
}

export function renderRoutes(routes, tokens = []) {
	const patterns = new Set(routes.map((r) => r.pattern));
	const byPattern = new Map();
	for (const t of tokens) {
		if (!patterns.has(t.pattern)) throw new Error(`token rule for ${t.pattern}, which is not a route`);
		tokenLabel(t);
		byPattern.set(t.pattern, t);
	}
	const out = [
		'# API routes',
		'',
		'<!-- GENERATED by scripts/gen-api-docs.mjs from apps/web/src/lib/pwa/sw/routes.fixture.json. Do not edit by hand. -->',
		'',
		`Every route the server registers (${routes.length} in total), grouped by who may call it. The list is generated from the route table, so it is complete but terse: for request and response shapes see [API reference](API-Reference), [API overview](API-Overview) and the fixtures under [docs/contracts](https://github.com/Elaktrato/qinqin/tree/develop/docs/contracts). Authentication and error codes: [API overview](API-Overview) and [API errors](API-Errors).`,
		'',
		'The **Token** column says whether a [personal access token](API-Access-tokens) may call the route: `read` (a read or write token), `write` (a write token only), with `(workspace)` when a token limited to one workspace must send `?workspace=<its id>`, and `(all)` when only a token for all workspaces may (a limited one gets 403 `token_workspace`). `—`: never with a token (403 `token_not_allowed`).',
		''
	];
	for (const [key, title, note] of ACCESS) {
		const rows = routes.filter((r) => r.access === key).map((r) => r.pattern).sort();
		if (rows.length === 0) continue;
		out.push(`## ${title} (${rows.length})`, '', note, '', '| Method | Path | Token |', '|---|---|---|');
		for (const p of rows) {
			const i = p.indexOf(' ');
			out.push(`| \`${p.slice(0, i)}\` | \`${p.slice(i + 1)}\` | ${tokenLabel(byPattern.get(p))} |`);
		}
		out.push('');
	}
	const known = new Set(ACCESS.map((a) => a[0]));
	const odd = routes.filter((r) => !known.has(r.access));
	if (odd.length) throw new Error(`unknown access class: ${[...new Set(odd.map((r) => r.access))].join(', ')}`);
	return out.join('\n');
}

export function renderErrors(catalogue) {
	const out = [
		'# API errors',
		'',
		'<!-- GENERATED by scripts/gen-api-docs.mjs from docs/contracts/auth/errors.json. Do not edit by hand. -->',
		'',
		'Every error body is JSON `{"error": code, "message": "English sentence"}`. Branch on the `error` code, never on the message: the `message` stays an English sentence for developers and logs, and clients show text translated by code from their own catalogue (`apiError.<code camelCased>`, `docs/contracts/i18n/README.md`). The catalogue below (`docs/contracts/auth/errors.json`) is the one list for every route: a test walks the whole route table and fails on an answer that is not this shape or uses a code missing here. Codes are only ever added; a client shows a generic text for a code it does not know yet. Extra members ride beside the two fixed ones where a meaning says so (`attemptsLeft`, `existingId`, `category`). A handler that fails unexpectedly answers 500 `internal` in the same shape. Only answers net/http gives before a request reaches the API are not JSON: a malformed request line, a 431 for headers that are too large, a TLS or proxy failure.',
		'',
		'| Code | Status | Meaning |',
		'|---|---|---|'
	];
	for (const [code, v] of Object.entries(catalogue)) {
		if (code.startsWith('_')) continue;
		out.push(`| \`${code}\` | ${v.status} | ${String(v.meaning).replaceAll('|', '\\|')} |`);
	}
	out.push('');
	return out.join('\n');
}

export function generate(root) {
	const routes = JSON.parse(readFileSync(resolve(root, 'apps/web/src/lib/pwa/sw/routes.fixture.json'), 'utf8'));
	const errors = JSON.parse(readFileSync(resolve(root, 'docs/contracts/auth/errors.json'), 'utf8'));
	const tokens = JSON.parse(readFileSync(resolve(root, 'docs/contracts/auth/tokens-routes.json'), 'utf8')).routes;
	return {
		'docs/wiki/API-Routes.md': renderRoutes(routes, tokens),
		'docs/wiki/API-Errors.md': renderErrors(errors)
	};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const args = process.argv.slice(2);
	const check = args.includes('--check');
	const root = resolve(args.find((a) => !a.startsWith('--')) ?? resolve(dirname(fileURLToPath(import.meta.url)), '..'));
	let stale = false;
	for (const [path, text] of Object.entries(generate(root))) {
		const file = resolve(root, path);
		if (check) {
			let have = '';
			try { have = readFileSync(file, 'utf8'); } catch { /* missing counts as stale */ }
			if (have !== text) { console.error(`stale: ${path} (run node scripts/gen-api-docs.mjs)`); stale = true; }
		} else {
			writeFileSync(file, text);
		}
	}
	process.exit(stale ? 1 : 0);
}
