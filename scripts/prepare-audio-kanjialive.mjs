#!/usr/bin/env node
// Builds the kanjialive-audio pack (type audio, format audio-index) from
// Kanji alive's published data:
//
//   node scripts/prepare-audio-kanjialive.mjs <ka_data.csv> <unzipped-dir> [<out>]
//        --license-file <legalcode.txt> [--version <v>] [--source-note <text>]
//
// <ka_data.csv> is language-data/ka_data.csv of
// https://github.com/kanjialive/kanji-data-media, <unzipped-dir> the
// unzipped audio-opus.zip (or its audio-opus folder). The n-th example
// word of a kanji (column `examples`) is the file <kname>_<NN>_<a..l>.opus;
// scripts/fetch-audio-kanjialive.sh checks that mapping against the data
// it downloads. <out> defaults to plugins/data-audio/kanjialive-audio,
// which is gitignored: neither the clips nor the index are ever committed.
// An example whose file is missing is skipped and counted.
//
// The output is deterministic (no timestamps), and the licence text is
// copied verbatim from --license-file.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACK_ID = 'kanjialive-audio';
const SUFFIXES = 'abcdefghijkl';
const SOURCE_URL = 'https://kanjialive.com';

/** parseCsv reads RFC 4180 text (quoted fields, doubled quotes, newlines inside quotes). */
export function parseCsv(text) {
	const rows = [];
	let row = [];
	let field = '';
	let quoted = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (quoted) {
			if (c === '"' && text[i + 1] === '"') {
				field += '"';
				i++;
			} else if (c === '"') quoted = false;
			else field += c;
		} else if (c === '"') quoted = true;
		else if (c === ',') {
			row.push(field);
			field = '';
		} else if (c === '\n' || c === '\r') {
			if (c === '\r' && text[i + 1] === '\n') i++;
			row.push(field);
			field = '';
			if (row.length > 1 || row[0] !== '') rows.push(row);
			row = [];
		} else field += c;
	}
	if (field !== '' || row.length) {
		row.push(field);
		rows.push(row);
	}
	return rows;
}

/**
 * exampleRows lists every example word of ka_data.csv as
 * {kname, form, reading, suffix}: the n-th example of a kanji has suffix
 * a..l. A word is written `形（よみ）`; the reading is the last full-width
 * parenthesis group, so a form may hold parentheses itself, and a
 * suru-verb stays as written (記述する / きじゅつする).
 */
export function exampleRows(csvText) {
	const [header, ...records] = parseCsv(csvText);
	const iName = header.indexOf('kname');
	const iExamples = header.indexOf('examples');
	if (iName < 0 || iExamples < 0) throw new Error('ka_data.csv: no kname/examples column');
	const out = [];
	for (const rec of records) {
		const kname = rec[iName];
		const examples = JSON.parse(rec[iExamples]);
		if (examples.length > SUFFIXES.length) throw new Error(`${kname}: ${examples.length} examples, at most ${SUFFIXES.length} (a-l) have audio`);
		examples.forEach(([word], i) => {
			const m = /^([^\t\n]+)（([^（）\t\n]+)）$/.exec(word);
			if (!m) throw new Error(`${kname}: example ${JSON.stringify(word)} is not "form（reading）"`);
			out.push({ kname, form: m[1], reading: m[2], suffix: SUFFIXES[i] });
		});
	}
	return out;
}

/** clipIndex maps `<kname>|<suffix>` to the file name found in audioDir. */
function clipIndex(audioDir) {
	const map = new Map();
	for (const name of readdirSync(audioDir)) {
		const m = /^(.*)_\d+_([a-z])\.opus$/.exec(name);
		if (m) map.set(`${m[1]}|${m[2]}`, name);
	}
	return map;
}

export function attributionText({ version, licenseNote }) {
	return `# Kanji alive example-word audio

Recordings of 6-12 common compound words for each of 1,235 kanji, spoken by
male and female native Japanese speakers. By Kanji alive (${SOURCE_URL}),
licensed under the Creative Commons Attribution 4.0 International License
(https://creativecommons.org/licenses/by/4.0/); the licence text is in LICENSE.

- Source of the recordings: https://media.kanjialive.com/examples_audio/audio-opus.zip
- Source of the word list and file names: https://github.com/kanjialive/kanji-data-media (language-data/ka_data.csv)
- Snapshot: ${version}
${licenseNote ? `- ${licenseNote}\n` : ''}
The files are unchanged copies of the published Opus files. This directory is
generated by scripts/fetch-audio-kanjialive.sh and is not part of the git
repository.
`;
}

/**
 * buildPack writes the pack to out (replacing it) and returns
 * {rows, skipped}. Throws before writing when the output would be unsafe.
 */
export function buildPack({ csvText, audioDir, out, licenseText, version = '1', licenseNote = '' }) {
	const rows = exampleRows(csvText);
	const clips = clipIndex(audioDir);
	const lines = ['kind\tform\treading\tfile\tlicense\tattribution\tsource'];
	const copies = [];
	let skipped = 0;
	for (const r of rows) {
		const file = clips.get(`${r.kname}|${r.suffix}`);
		if (!file) {
			skipped++;
			continue;
		}
		lines.push(['term', r.form, r.reading, `audio/${file}`, '', '', ''].join('\t'));
		copies.push(file);
	}
	rmSync(out, { recursive: true, force: true });
	mkdirSync(join(out, 'audio'), { recursive: true });
	for (const file of new Set(copies)) copyFileSync(join(audioDir, file), join(out, 'audio', file));
	const manifest = {
		id: PACK_ID,
		name: 'Kanji alive example-word audio',
		version,
		type: 'audio',
		language: 'ja',
		license: 'CC BY 4.0',
		attribution: 'Kanji alive (https://kanjialive.com), CC BY 4.0',
		notice:
			'Recordings of common example words for 1,235 kanji, spoken by male and female native Japanese speakers, from [Kanji alive](https://kanjialive.com) under CC BY 4.0. Japanese words without a recording fall back to your device voice.',
		format: 'audio-index',
	};
	writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
	writeFileSync(join(out, 'index.tsv'), lines.join('\n') + '\n');
	writeFileSync(join(out, 'LICENSE'), licenseText);
	writeFileSync(join(out, 'ATTRIBUTION.md'), attributionText({ version, licenseNote }));
	return { rows: copies.length, skipped };
}

function usage(msg) {
	console.error(`prepare-audio-kanjialive: ${msg}
usage: node scripts/prepare-audio-kanjialive.mjs <ka_data.csv> <unzipped-dir> [<out>] --license-file <legalcode.txt> [--version <v>] [--note <text>]`);
	process.exit(2);
}

function main(argv) {
	const pos = [];
	const opt = {};
	for (let i = 0; i < argv.length; i++) {
		if (argv[i].startsWith('--')) opt[argv[i].slice(2)] = argv[++i];
		else pos.push(argv[i]);
	}
	if (pos.length < 2 || pos.length > 3) usage('expected <ka_data.csv> <unzipped-dir> [<out>]');
	if (!opt['license-file']) usage('--license-file is required: the pack carries the licence text verbatim');
	const repo = resolve(fileURLToPath(new URL('..', import.meta.url)));
	const out = resolve(pos[2] ?? join(repo, 'plugins', 'data-audio', PACK_ID));
	if ((out + sep).startsWith(join(repo, 'plugins', 'data') + sep)) usage('refusing to write into plugins/data (committed packs); use plugins/data-audio');
	let audioDir = resolve(pos[1]);
	if (existsSync(join(audioDir, 'audio-opus')) && statSync(join(audioDir, 'audio-opus')).isDirectory()) audioDir = join(audioDir, 'audio-opus');
	const res = buildPack({
		csvText: readFileSync(pos[0], 'utf8'),
		audioDir,
		out,
		licenseText: readFileSync(opt['license-file'], 'utf8'),
		version: opt.version ?? '1',
		licenseNote: opt.note ?? '',
	});
	console.log(`${PACK_ID}: ${res.rows} clips, ${res.skipped} skipped (no audio file) -> ${out}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
