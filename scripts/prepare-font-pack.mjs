#!/usr/bin/env node
// Build a hanzi/kanji font pack (type font, format font-slices; see
// docs/contracts/fonts/README.md) from a pinned upstream face:
//
//   node scripts/prepare-font-pack.mjs --source <id> --out <dir>
//        [--face sans|serif|kai] [--script Hans|Hant|Jpan] [--cache <dir>]
//        [--font <file.ttf>]... [--license <OFL.txt>]
//   node scripts/prepare-font-pack.mjs --slices [--check]
//
// Run `npm --prefix scripts/fonts ci` first: the subsetter (subset-font,
// harfbuzzjs; WOFF2 through fontverter/wawoff2) is a build-time tool of
// this script only, never a dependency of the app.
//
// --source names a row of SOURCES below: the upstream files at a fixed
// commit or release with the sha256 of each font file and of its OFL.txt;
// the script refuses to build when a file differs. The files are
// downloaded into --cache (default plugins/data-fonts/.cache), or read
// from --font/--license (still checked against the pins). --face and
// --script, when given, must match the source.
//
// Each font is cut into WOFF2 slices by the slice table
// scripts/testdata/font-slices.json (generated by --slices from the
// bundled level lists, --slices --check verifies it): slice 0 holds ASCII,
// CJK punctuation, fullwidth forms (and kana for Jpan); then the
// characters of the level lists in rank order in chunks of 200; then the
// font's remaining code points in ascending order in chunks of 500. The
// variation axes are kept, so one slice set serves every weight.
//
// Every slice is a Modified Version under the SIL OFL 1.1 and is renamed
// (plan Ruling 3): the family, full, PostScript and unique names become
// `qinqin <Face> <SC|TC|JP>`; the copyright (name ID 0) and licence (13,
// 14) are kept; trademark, manufacturer, designer, description and URL
// names are dropped. The pack carries the original's OFL.txt byte for byte
// as LICENSE and an ATTRIBUTION.md naming the original and the change.
//
// Packs are large and are never committed (plugins/data-fonts/ is
// gitignored); install one with the admin upload or `qinqin seed`.
